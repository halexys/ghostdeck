#!/usr/bin/env python3
"""
Model history for the Models tab: when each firmware prefix was first recognised and when
its model became Tested. The app reads data/model-history.json (embedded in the exe) and the
signed models.json carries the dates per model, so the growth chart, the timeline and the
NEW badge follow the database with no hand edits.

    python tools/model-history.py            # add today's date for anything new (run after
                                             # every Devices.cs change, before the build/dump)
    python tools/model-history.py --check    # CI: exit 1 when a prefix or a Tested model
                                             # has no date yet
    python tools/model-history.py --backfill # one-off: rebuild every date from git history

Source of the current list: the BuiltIn table in Core/Devices.cs (prefixes + Tier, default
Tested). Dates are kept per PREFIX, so a later rename or merge of an entry keeps its history;
a model's dates are the earliest over its prefixes.
"""
import datetime, json, os, re, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEVICES = os.path.join(ROOT, "Core", "Devices.cs")
HISTORY = os.path.join(ROOT, "data", "model-history.json")

PREFIX_RE = re.compile(r'FirmwarePrefixes\s*=\s*new\[\]\s*\{([^}]*)\}')
TIER_RE = re.compile(r'Tier\s*=\s*Tier\.(\w+)')


def strip_comments(src):
    out = []
    for line in src.splitlines():
        i = line.find("//")
        out.append(line if i < 0 else line[:i])
    return "\n".join(out)


def parse_devices(src):
    """[(prefixes, tested)] for every entry of the BuiltIn table."""
    src = strip_comments(src)
    start = src.find("BuiltIn")
    if start < 0:
        start = 0
    body = src[start:]
    hits = list(PREFIX_RE.finditer(body))
    entries = []
    for k, m in enumerate(hits):
        seg_end = hits[k + 1].start() if k + 1 < len(hits) else len(body)
        seg = body[m.start():seg_end]
        prefixes = re.findall(r'"([^"]+)"', m.group(1))
        t = TIER_RE.search(seg)
        tested = (t is None) or t.group(1) == "Tested"
        if prefixes:
            entries.append((prefixes, tested))
    return entries


def load():
    if not os.path.exists(HISTORY):
        return {}
    with open(HISTORY, encoding="utf-8") as f:
        return json.load(f).get("prefixes", {})


def save(hist):
    data = {
        "comment": "Generated by tools/model-history.py - do not edit by hand. "
                   "added = first recognised, tested = first seen as Tested.",
        "prefixes": {k: hist[k] for k in sorted(hist)},
    }
    with open(HISTORY, "w", encoding="utf-8", newline="\n") as f:
        json.dump(data, f, indent=2, ensure_ascii=False)
        f.write("\n")


def git(*args):
    return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True,
                          encoding="utf-8").stdout


def backfill():
    hist = {}
    log = git("log", "--reverse", "--format=%H %cs", "--", "Devices.cs", "Core/Devices.cs").split("\n")
    for line in log:
        if not line.strip():
            continue
        sha, date = line.split()
        src = git("show", f"{sha}:Core/Devices.cs") or git("show", f"{sha}:Devices.cs")
        if not src:
            continue
        for prefixes, tested in parse_devices(src):
            for p in prefixes:
                e = hist.setdefault(p, {"added": date})
                if tested and "tested" not in e:
                    e["tested"] = date
    # an entry demoted later keeps its first Tested date only while it is still Tested now
    return hist


def update(hist, entries, today):
    changed = []
    for prefixes, tested in entries:
        for p in prefixes:
            e = hist.get(p)
            if e is None:
                hist[p] = e = {"added": today}
                changed.append(f"added {p}")
            if tested and "tested" not in e:
                # a new prefix on an already Tested entry inherits the entry's earliest date
                older = [hist[q]["tested"] for q in prefixes if q in hist and "tested" in hist[q]]
                e["tested"] = min(older) if older else today
                changed.append(f"tested {p}")
    return changed


def main():
    with open(DEVICES, encoding="utf-8") as f:
        entries = parse_devices(f.read())
    if "--check" in sys.argv:
        hist = load()
        missing = []
        for prefixes, tested in entries:
            for p in prefixes:
                if p not in hist:
                    missing.append(f"{p}: no added date")
            if tested and not any("tested" in hist.get(p, {}) for p in prefixes):
                missing.append(f"{prefixes[0]}: Tested without a tested date")
        # every thanked login needs its reports (Models tab lists them per person)
        with open(DEVICES, encoding="utf-8") as f:
            src = strip_comments(f.read())
        for cm in re.finditer(r'Credit = "([^"]*)"[^\n]*\n?\s*(?:CreditIssues = Issues\("([^"]*)"\))?', src):
            logins = [x.strip() for x in re.split(r"[,&]", cm.group(1)) if x.strip()]
            spec = cm.group(2) or ""
            have = {p.split(":")[0].strip().lower() for p in spec.split(";") if ":" in p}
            for lg in logins:
                if lg.lower() not in have:
                    missing.append(f"{lg}: thanked but no report numbers in CreditIssues")
        if missing:
            print("model-history.json is behind Devices.cs - run: python tools/model-history.py")
            for m in missing:
                print("  " + m)
            return 1
        print(f"model history OK ({len(entries)} models)")
        return 0
    if "--backfill" in sys.argv:
        hist = backfill()
    else:
        hist = load()
    today = datetime.date.today().isoformat()
    changed = update(hist, entries, today)
    save(hist)
    tested = sum(1 for _, t in entries if t)
    print(f"{len(entries)} models ({tested} Tested), {len(hist)} prefixes in history")
    for c in changed:
        print("  " + c)
    return 0


if __name__ == "__main__":
    sys.exit(main())
